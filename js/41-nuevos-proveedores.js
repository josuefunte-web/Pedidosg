function addMissingSuppliers(){
  if(!fbDb) return;
  fbDb.ref('suppliers').once('value', snap=>{
    const existing = snap.val() || {};
    const updates = {};
    Object.entries(NEW_SUPPLIERS).forEach(([id, sup])=>{
      if(!existing[id]) updates[id] = sup;
    });
    if(Object.keys(updates).length > 0){
      fbDb.ref('suppliers').update(updates).then(()=>{
        toast('Nuevos proveedores añadidos: '+Object.keys(updates).map(k=>NEW_SUPPLIERS[k].name).join(', '),'#16a34a');
      });
    }
  });
}

function updateCoreSuppliers(){
  if(!fbDb) return;
  fbDb.ref('suppliers').once('value', snap=>{
    const existing = snap.val() || {};
    const updates = {};
    // Always update bencar to latest Excel prices
    updates['bencar'] = DEFAULT_SUPS['bencar'];
    // Update ismael if products missing or wrong prefix
    const curIsmael = existing['ismael'];
    const defIsmael = DEFAULT_SUPS['ismael'];
    if(!curIsmael || !curIsmael.products || !curIsmael.products[0] || !String(curIsmael.products[0].id).startsWith('ix')){
      updates['ismael'] = defIsmael;
    }
    if(Object.keys(updates).length > 0){
      fbDb.ref('suppliers').update(updates).then(()=>{
        toast('Tarifas de Bencar e Ismael actualizadas','#16a34a');
      });
    }
  });
}
